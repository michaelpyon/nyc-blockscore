// Helper: create a simple 2-point line segment
function seg(
  lat1: number,
  lng1: number,
  lat2: number,
  lng2: number
): GeoJSON.LineString {
  return {
    type: "LineString",
    coordinates: [
      [lng1, lat1],
      [lng2, lat2],
    ],
  };
}

